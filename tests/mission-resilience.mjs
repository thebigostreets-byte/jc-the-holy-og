import assert from 'node:assert/strict';
import {createMissionTracker,JC_MISSION_STORAGE_KEY} from '../jc-missions.js';
const map=new Map();
const storage={getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,value)};
let checks=0;
function equal(actual,expected,label){assert.deepEqual(actual,expected,label);checks++}
const saved={version:1,counts:{lights:-7,prayers:'3',buildings:1e300,people:null,regions:NaN},visited:['strip'],startedAt:1,updatedAt:2};
map.set(JC_MISSION_STORAGE_KEY,JSON.stringify(saved));
const m=createMissionTracker(storage);
equal(m.getSnapshot().missions.map(x=>x.value),[0,0,5,0,0],'corrupt saved progress normalized');
equal(m.add('lights',NaN),false,'NaN increment rejected');
equal(m.add('lights',Infinity),false,'infinite increment rejected');
equal(m.add('lights',-1),false,'negative increment rejected');
equal(m.add('lights',0),false,'zero increment rejected');
equal(m.add('lights',2),true,'valid progress increment');
equal(m.getSnapshot().missions[0].value,2,'valid progress preserved');
let reached=0;
m.onChange(()=>{throw new Error('UI listener crashed')});
m.onChange(()=>{reached++});
equal(m.add('lights',1),true,'listener crash does not interrupt mission');
equal(reached,1,'later listener still receives event');
equal(m.getSnapshot().missions[0].value,3,'mission state survives listener exception');
m.definitions[0].target=1;
equal(m.getSnapshot().missions[0].target,8,'external metadata mutation cannot change mission rules');
const reloaded=createMissionTracker(storage);
equal(reloaded.getSnapshot().missions[0].value,3,'valid progress survives reload');
reloaded.reset();
equal(reloaded.getSnapshot().missions[0].value,0,'reset clears mission progress');
console.log(`${checks} mission resilience assertions passed`);
