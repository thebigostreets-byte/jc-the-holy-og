import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createMissionTracker,JC_MISSION_STORAGE_KEY} from '../jc-missions.js';
const storage=(payload)=>{
  let saved=payload===undefined?null:JSON.stringify(payload),writes=0;
  return {getItem:()=>saved,setItem:(_k,value)=>{saved=value;writes++;},get writes(){return writes;}};
};
const s=storage({version:1,counts:{lights:Infinity,prayers:-30,buildings:'2.9',people:'not-a-number',regions:100000},visited:[' strip ','strip',null,{},'','airport','airport',7],startedAt:'oops',updatedAt:-10});
const m=createMissionTracker(s);
assert.deepEqual(m.getSnapshot().missions.map(x=>x.value),[0,0,2,0,4],'malformed persisted counters are finite, integral and bounded');
assert.deepEqual(m.getSnapshot().visited,['strip','airport','7'],'visits are normalized, deduplicated and bounded');
assert.ok(Number.isFinite(m.getState().startedAt)&&m.getState().startedAt>0,'invalid timestamp is repaired');
assert.ok(Number.isFinite(m.getState().updatedAt)&&m.getState().updatedAt>0,'invalid update timestamp is repaired');
const before=s.writes;
for(const amount of [NaN,Infinity,-Infinity,-1,0,.5,'4',null,{},[]])assert.equal(m.add('lights',amount),false);
assert.equal(s.writes,before,'invalid progress cannot write a corrupted save');
assert.equal(m.add('lights',2.8),true);
assert.equal(m.getSnapshot().missions[0].value,2,'fractional increments count only completed units');
assert.equal(m.add('lights',999999),true);
assert.equal(m.getSnapshot().missions[0].value,8,'progress remains capped');
assert.equal(m.add('lights',1),false,'completed missions do not persist again');
assert.equal(m.visit(' strip '),false,'normalized duplicates cannot advance region progress');
assert.equal(m.visit('   '),false,'blank visits are rejected');
assert.equal(m.visit({id:'fake'}),false,'object keys are rejected');
assert.equal(m.visit('new district'),true);
assert.ok(m.getSnapshot().visited.includes('new district'));
assert.equal(m.definitions[0].target,8);
assert.throws(()=>{m.definitions[0].target=999;},TypeError,'mission definitions cannot be mutated by callers');
assert.throws(()=>{m.definitions.push({id:'fake'});},TypeError,'mission catalog cannot be extended by callers');
const second=storage({version:1,counts:{lights:4},visited:['a','a',' b ','b',...Array.from({length:50},(_,i)=>`tile${i}`)]});
const loaded=createMissionTracker(second);
assert.equal(loaded.getSnapshot().visited.length,32,'persisted visits obey retention cap');
assert.equal(new Set(loaded.getSnapshot().visited).size,32,'persisted visits contain no duplicates');
let called=0;const oldWarn=console.warn;console.warn=()=>{};
try{
  loaded.onChange(()=>{throw new Error('UI failed');});
  loaded.onChange(()=>called++);
  assert.equal(loaded.add('lights',1),true);
  assert.equal(called,1,'one broken UI subscriber does not block other subscribers');
}finally{console.warn=oldWarn;}
assert.equal(createMissionTracker(storage({version:2,counts:{lights:8}})).getSnapshot().missions[0].value,0,'unsupported save versions are rejected');
assert.equal(fs.readFileSync(new URL('../jc-missions.js',import.meta.url),'utf8'),fs.readFileSync(new URL('../dist/client/jc-missions.js',import.meta.url),'utf8'),'deployable mission source matches');
console.log('PASS: mission save normalization, bounded increments, visit deduplication, subscriber isolation and source/dist parity');
